function svgMarkup(name, className) {
  const inner = PATHS[name] || '';
  return (
    `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`
  );
}

/** String SVG do ícone — para embutir via innerHTML/`html` (conteúdo confiável). */
export function iconHtml(name, className = 'icon') {
  return svgMarkup(name, className);
}

/** Elemento SVG do ícone — para passar como filho de `el(...)`. */
export function icon(name, className = 'icon') {
  const tpl = document.createElement('template');
  tpl.innerHTML = svgMarkup(name, className);
  return tpl.content.firstChild;
}

/** Substitui o conteúdo de um nó pelo ícone (usado em botões que trocam de estado). */
export function setIcon(node, name, className = 'icon') {
  node.replaceChildren(icon(name, className));
}
